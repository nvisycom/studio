/** A reusable `DisplayNames`, cached per (locale, type). */
const displayNamesCache = new Map<string, Intl.DisplayNames | null>();
function displayNames(
	type: "region" | "language",
	locale: string,
): Intl.DisplayNames | null {
	const key = `${locale}:${type}`;
	let dn = displayNamesCache.get(key);
	if (dn === undefined) {
		try {
			dn = new Intl.DisplayNames([locale], { type });
		} catch {
			dn = null; // environment without full ICU data
		}
		displayNamesCache.set(key, dn);
	}
	return dn;
}

/** Localized country name for an ISO-3166 code (`"PL"` → "Poland"), or `null`. */
export function regionName(code: string, locale = "en"): string | null {
	try {
		return displayNames("region", locale)?.of(code.toUpperCase()) ?? null;
	} catch {
		return null; // malformed code
	}
}

/** Localized language name for a BCP-47 tag (`"en"` → "English"), or `null`. */
export function languageName(tag: string, locale = "en"): string | null {
	try {
		return displayNames("language", locale)?.of(tag.toLowerCase()) ?? null;
	} catch {
		return null;
	}
}
